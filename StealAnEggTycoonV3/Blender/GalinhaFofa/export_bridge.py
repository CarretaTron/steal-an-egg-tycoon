"""Split the Blender geometry bridge below Studio's 200,000-character source limit."""
import json
from pathlib import Path

def write_bridge(library_path):
    library_path=Path(library_path)
    shared=library_path.parent.parent/'Shared'
    data=json.loads(library_path.read_text(encoding='utf-8'))
    chicken={k:v for k,v in data['Meshes'].items() if k.startswith('Chicken_')}
    data['Meshes']={k:v for k,v in data['Meshes'].items() if k not in chicken}
    chunks=[];current={}
    for key,value in chicken.items():
        candidate={**current,key:value}
        if len(json.dumps(candidate,separators=(',',':')))>135000 and current:
            chunks.append(current);current={key:value}
        else: current=candidate
    if current:chunks.append(current)
    names=[]
    for i,chunk in enumerate(chunks,1):
        name=f'ChickenGeometry{i}';names.append(name)
        text="-- Generated Blender chicken meshes, part "+str(i)+".\nreturn game:GetService('HttpService'):JSONDecode([==["+json.dumps(chunk,separators=(',',':'))+"]==])\n"
        assert len(text)<190000
        (shared/(name+'.luau')).write_text(text,encoding='utf-8')
    text="-- Generated by Blender/GalinhaFofa/export_bridge.py; keep mesh chunks beside this module.\nlocal data=game:GetService('HttpService'):JSONDecode([==["+json.dumps(data,separators=(',',':'))+"]==])\n"
    text+='for _,name in ipairs({'+','.join(repr(n) for n in names)+'}) do\n for key,value in pairs(require(script.Parent:WaitForChild(name))) do data.Meshes[key]=value end\nend\nreturn data\n'
    assert len(text)<190000
    (shared/'GeometryData.luau').write_text(text,encoding='utf-8')
    return names

if __name__=='__main__':
    print(write_bridge(Path(__file__).resolve().parent.parent/'geometry.json'))
